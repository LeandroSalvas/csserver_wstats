const i18nUtils = {
  currentLang: 'pt',

  init() {
    const stored = localStorage.getItem('lang')
    const browserLang = navigator.language.toLowerCase().startsWith('en') ? 'en' : 'pt'
    this.currentLang = stored || browserLang
    this.apply()
  },

  t(key) {
    const keys = key.split('.')
    let val = i18n[this.currentLang]
    for (const k of keys) {
      val = val?.[k]
      if (val === undefined) break
    }
    return val !== undefined ? val : key
  },

  setLang(lang) {
    this.currentLang = lang
    localStorage.setItem('lang', lang)
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en'
    this.apply()
  },

  apply() {
    document.documentElement.lang = this.currentLang === 'pt' ? 'pt-BR' : 'en'
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.dataset.i18n
      el.textContent = this.t(key)
    })
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const key = el.dataset.i18nHtml
      el.innerHTML = this.t(key)
    })
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.dataset.i18nPlaceholder
      el.placeholder = this.t(key)
    })
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.dataset.i18nTitle
      el.title = this.t(key)
    })
    document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
      el.setAttribute('aria-label', this.t(el.dataset.i18nAriaLabel))
    })
    document.dispatchEvent(new CustomEvent('i18n applied'))
  },

  getToggleHtml() {
    if (this.currentLang === 'pt') {
      return '<b>PT</b> | EN'
    }
    return 'PT | <b>EN</b>'
  }
}
